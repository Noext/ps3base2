#!/usr/bin/env python3
"""Generate the LV2 syscall table from the specification in refs/.

Every number RPCS3 dispatches is listed; the ones we do not implement report
ENOSYS. Implementing only what a program asks for produces a kernel that works
for one game and fails silently for the next.

refs/rpcs3 is GPL-2 and is read-only: only NUMBERS and NAMES are taken from it,
which are facts about the PS3. No expression is copied.
"""
import os, re, sys

# The LV2 specification is read from a copy of RPCS3 the user has checked out.
# Only the syscall NUMBERS and NAMES are taken from it -- facts about the PS3,
# not code -- so nothing of RPCS3's licence travels with the output.
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REF  = os.environ.get("PS3BASE_LV2_SPEC",
                      os.path.join(ROOT, "refs/rpcs3/rpcs3/Emu/Cell/lv2/lv2.cpp"))
OUT  = os.environ.get("PS3BASE_LV2_OUT",
                      os.path.join(ROOT, "runtime/src/lv2/syscall_table.h"))
ROW  = re.compile(r"^\s*BIND_SYSC\(\s*([A-Za-z0-9_]+)\s*\),?\s*//\s*(\d+)")

def parse():
    rows = []
    for line in open(REF, encoding="utf-8", errors="replace"):
        m = ROW.match(line)
        if m:
            rows.append((int(m.group(2)), m.group(1)))
    return rows

def implemented(number, name):
    d = os.path.join(ROOT, "runtime", "src", "lv2")
    if not os.path.isdir(d):
        return False
    # This tree registers handlers as LV2_SYSCALL(<num>, <name>), so a syscall
    # is implemented when that macro names it -- not when a function happens to
    # be called like it.
    #
    # MMAPPER_SYSCALL is the same registration with a logging wrapper around the
    # body (runtime/src/lv2/mmapper.cpp), so it counts. Without this the table
    # claimed the eight sys_mmapper entries were unimplemented while they ran.
    pat = re.compile(r"(?:LV2_|MMAPPER_)SYSCALL\(\s*" + re.escape(str(number)) + r"\s*,")
    for fn in sorted(os.listdir(d)):
        if fn.endswith((".c", ".cpp")):
            try:
                if pat.search(open(os.path.join(d, fn), encoding="utf-8", errors="replace").read()):
                    return True
            except OSError:
                pass
    return False

GROUPS = [
    ("process", 1, 40), ("ppu_thread", 41, 79), ("semaphore", 80, 99),
    ("event_flag", 100, 129), ("event_queue", 130, 139), ("timer", 140, 169),
    ("spu_thread", 170, 260), ("memory", 300, 360), ("tty", 400, 405),
    ("filesystem", 430, 479), ("prx", 480, 499), ("modules", 500, 559),
]
def group_of(n):
    for name, lo, hi in GROUPS:
        if lo <= n <= hi:
            return name
    return "other"

def main():
    rows = parse()
    if len(rows) < 400:
        print("gen: only %d rows parsed from %s; set PS3BASE_LV2_SPEC to a copy of"
              " RPCS3's lv2.cpp" % (len(rows), REF), file=sys.stderr)
        return 1

    impl = {n: implemented(n, name) for n, name in rows}

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("/* GENERATED by tools/gen_syscall_table.py -- do not edit.\n *\n"
                " * Every LV2 syscall number the specification dispatches, with whether\n"
                " * this kernel implements it. Numbers and names are facts about the PS3;\n"
                " * they are taken from refs/rpcs3, which is otherwise never used.\n */\n")
        f.write("#ifndef PS3BASE_SYSCALL_TABLE_H\n#define PS3BASE_SYSCALL_TABLE_H\n\n")
        f.write("typedef struct { unsigned num; const char* name; int implemented; } syscall_info;\n\n")
        f.write("static const syscall_info k_syscall_spec[] = {\n")
        for n, name in sorted(rows):
            f.write('    { %u, "%s", %d },\n' % (n, name, 1 if impl[n] else 0))
        f.write("};\n\nstatic const unsigned k_syscall_spec_count = (unsigned)(sizeof k_syscall_spec / sizeof k_syscall_spec[0]);\n")
        f.write("\n#endif\n")

    total = len(rows)
    done  = sum(1 for n in impl if impl[n])
    print("gen_syscall_table: %d syscalls listed, %d implemented (%.1f%%)"
          % (total, done, 100.0 * done / total))
    for gname, lo, hi in GROUPS:
        g = [n for n, _ in rows if lo <= n <= hi]
        if not g:
            continue
        gd = sum(1 for n in g if impl[n])
        print("  %-12s %3d/%-3d  %5.1f%%" % (gname, gd, len(g), 100.0 * gd / len(g)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
